const DICTIONARIES: Record<Language, Record<TextKey, string>> = {
  en: EN,
  pt: PT,
};

let current: Language = 'en';

/** The language for a setting value and Obsidian's own language code ("en", "pt", "pt-BR" …). */
export function resolveLanguage(
  setting: LanguageSetting,
  obsidianLocale: string,
): Language {
  if (setting !== 'auto') return setting;
  return obsidianLocale.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export function setLanguage(language: Language): void {
  current = language;
}

export function currentLanguage(): Language {
  return current;
}

/** The text for a key in the current language, with {name} placeholders filled in. English is the fallback. */
export function t(
  key: TextKey,
  params?: Record<string, string | number>,
): string {
  const text = DICTIONARIES[current][key] || EN[key];
  return params
    ? text.replace(/\{(\w+)\}/g, (whole, name: string) =>
        name in params ? String(params[name]) : whole,
      )
    : text;
}

